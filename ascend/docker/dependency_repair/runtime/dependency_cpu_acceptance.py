def opencv_layout():
    records={}
    for name in ('opencv-python','opencv-python-headless'):
        d=metadata.distribution(name)
        root=Path(getattr(d,'_path','')).resolve().parent
        if d.version!='4.11.0.86':raise RuntimeError('Actual OpenCV distribution version differs')
        payload=0;total=0
        for relative in d.files or []:
            path=Path(d.locate_file(relative))
            # Bytecode caches with no source-wheel hash are generated by Python.
            if relative.hash is None and path.suffix=='.pyc':continue
            if not path.is_file():raise RuntimeError('Actual OpenCV payload missing: '+str(path))
            if relative.hash is not None:
                h=hashlib.new(relative.hash.mode)
                with path.open('rb') as stream:
                    for block in iter(lambda:stream.read(8*1024**2),b''):h.update(block)
                if base64.urlsafe_b64encode(h.digest()).rstrip(b'=').decode()!=relative.hash.value:
                    raise RuntimeError('Actual OpenCV RECORD payload bytes changed: '+str(path))
                payload+=1
            total+=path.stat().st_size
        if not payload:raise RuntimeError('Actual OpenCV payload inventory unavailable')
        records[name]={'prefix':str(root),'metadata_path':str(getattr(d,'_path','')),
          'verified_hashed_payload_files':payload,'inventory_bytes':total,'version':d.version}
    if records['opencv-python']['prefix']!='/opt/worldengine-dependency-fix':raise RuntimeError('Full OpenCV is not the fresh overlay')
    if records['opencv-python-headless']['prefix']!='/opt/conda/envs/bevformer/lib/python3.10/site-packages':raise RuntimeError('Original headless prefix differs')
    import cv2
    active=Path(cv2.__file__).resolve()
    if not active.is_relative_to(Path(records['opencv-python']['prefix'])):raise RuntimeError('Actual cv2 module did not resolve to full overlay')
    records['actual_cv2_module']=str(active)
    return records

def main():
    p=argparse.ArgumentParser(description=__doc__,allow_abbrev=False)
    p.add_argument('--output',type=Path,required=True)
    a=p.parse_args()
    if a.output.exists():raise RuntimeError('Fresh receipt required')
    r={'result':'running','scope':'CPU package/runtime import checks, not NPU/model acceptance',
      'modules':{},'checks':{},'failures':[],'sys_path':sys.path,
      'helper_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}
    try:
        if list(Path('/dev').glob('davinci[0-9]*')):raise RuntimeError('CPU-only container required')
        if os.environ.get('TORCH_DEVICE_BACKEND_AUTOLOAD')!='0':raise RuntimeError('Backend autoload must be disabled')
        for name,version in EXPECTED.items():
            actual=metadata.version(name)
            r['checks']['distribution_'+name]={'actual':actual,'expected':version,'pass':actual==version}
            if actual!=version:r['failures'].append('Wrong distribution version: '+name)
        from packaging.tags import parse_tag,sys_tags
        te=metadata.distribution('te')
        raw_wheel=te.read_text('WHEEL')
        if raw_wheel is None:raise RuntimeError('TE WHEEL metadata unavailable; ABI unverified')
        declared=Parser().parsestr(raw_wheel).get_all('Tag',[])
        wheel_tags=set().union(*(parse_tag(t) for t in declared)) if declared else set()
        compatible=bool(wheel_tags & set(sys_tags()))
        r['checks']['TE_wheel_ABI']={'version':te.version,'metadata_path':str(getattr(te,'_path','unknown')),
          'declared_tags':declared,'current_python':sys.version,'pass':compatible,
          'WHEEL_sha256':hashlib.sha256(raw_wheel.encode()).hexdigest()}
        if not compatible:r['failures'].append('TE wheel tags do not match the actual interpreter/platform')
        r['checks']['actual_distinct_prefix_OpenCV_layout']=opencv_layout()
        import argparse as std_argparse
        std=Path(sysconfig.get_path('stdlib')).resolve()
        origin=Path(std_argparse.__file__).resolve()
        if origin!=std/'argparse.py':raise RuntimeError('argparse backport shadows Python stdlib')
        r['checks']['argparse_stdlib']={'file':str(origin),'pass':True}
        # Namespace merging must retain the previously installed google.auth.
        for name in ('numpy','cv2','google.protobuf','google.auth','importlib_metadata',
          'regex','safetensors','hf_xet','diffusers','huggingface_hub','tensorboard',
          'rasterio','fiona','shapely','geopandas','nuplan','torch','torch_npu','mmcv'):
            try:
                m=importlib.import_module(name)
                r['modules'][name]={'file':getattr(m,'__file__',None),'version':getattr(m,'__version__',None),'pass':True}
            except Exception as error:
                r['modules'][name]={'pass':False,'error':repr(error)}
                r['failures'].append('Import failed: '+name)
        import numpy as np
        import cv2
        image=np.arange(48,dtype=np.uint8).reshape(4,4,3)
        encoded,jpg=cv2.imencode('.jpg',image)
        if not encoded or cv2.imdecode(jpg,cv2.IMREAD_COLOR).shape!=(4,4,3):raise RuntimeError('cv2 JPEG roundtrip failed')
        if cv2.resize(image,(2,2)).shape!=(2,2,3):raise RuntimeError('cv2 resize failed')
        from google.protobuf.struct_pb2 import Struct
        message=Struct();message.update({'probe':1});copy=Struct();copy.ParseFromString(message.SerializeToString())
        if copy!=message:raise RuntimeError('Protobuf real message roundtrip failed')
        r['checks']['cv2_and_protobuf_runtime']={'pass':True}
        import torch
        import torch_npu
        r['NPU_initialized']=torch_npu.npu.is_initialized()
        r['CUDA_initialized']=torch.cuda.is_initialized()
        if r['NPU_initialized'] or r['CUDA_initialized']:raise RuntimeError('Unexpected accelerator initialization')
    except BaseException as error:
        r['failures'].append(repr(error));r['traceback']=traceback.format_exc()
    try:
        done=subprocess.run([sys.executable,'-m','pip','check'],text=True,capture_output=True,timeout=60)
        r['pip_check']={'exit_code':done.returncode,'stdout':done.stdout,'stderr':done.stderr}
        if done.returncode:r['failures'].append('pip check is not clean; full dependency acceptance denied')
    except BaseException as error:
        r['pip_check']={'exit_code':None,'error':repr(error)}
        r['failures'].append('pip check did not complete; full dependency acceptance denied')
    r['result']='pass_complete_CPU_dependency_acceptance' if not r['failures'] else 'failed_or_partial_CPU_dependency_acceptance'
    a.output.parent.mkdir(parents=True,exist_ok=True)
    a.output.write_bytes((json.dumps(r,indent=2)+'\n').encode())
    print(json.dumps({'result':r['result'],'failures':r['failures'],'output':str(a.output)}))
    return 0 if not r['failures'] else 1

if __name__=='__main__':raise SystemExit(main())
